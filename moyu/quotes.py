"""按等级随机配一句摸鱼语录（同一分数结果稳定）。"""

QUOTES = {
    "卷王本王": [
        "你不是在加班，你是在给未来的自己攒黑眼圈。",
        "工位灯亮得比路灯还久，老板看了都心疼电费。",
        "今天的你，是 PPT 里最勤劳的那一页。",
    ],
    "正常打工": [
        "摸鱼不是偷懒，是给大脑做一次磁盘整理。",
        "该干干、该歇歇，稳如老狗。",
        "上班上出了节奏感，这很难得。",
    ],
    "摸鱼带师": [
        "键盘敲得很响，内容很空，这是艺术。",
        "你已经掌握了「看起来很忙」的核心技术栈。",
        "屏幕切换比心跳还快，切换得行云流水。",
    ],
    "赛博隐士": [
        "你在工位，但工位不在你心里。",
        "今天的产出主要集中在了设想阶段。",
        "同事以为你在写代码，其实你在写人生。",
    ],
}


def quote_of(level, score):
    """按等级取一句语录，用 score 做确定性选择，保证可复现。"""
    bucket = QUOTES.get(level) or QUOTES["正常打工"]
    return bucket[score % len(bucket)]
